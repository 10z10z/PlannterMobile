/** The scheme a new install wears: the app's own green and gold. */
export const DEFAULT_SCHEME = 'plannter';

/** A stored choice as one of the six, falling back to the default. */
export function normalizeScheme(value) {
  return COLOR_SCHEMES.some((scheme) => scheme.value === value) ? value : DEFAULT_SCHEME;
}

export function schemeOf(value) {
  return COLOR_SCHEMES.find((scheme) => scheme.value === normalizeScheme(value));
}

/** The MD3 colours for a scheme in the mode currently being shown. */
export function schemeColors(value, isDark) {
  const scheme = schemeOf(value);
  return isDark ? scheme.dark : scheme.light;
}

/**
 * The same colours in the shape React Navigation asks for, so the navigator's
 * own surfaces — the tab bar background, the stack header — are not left on
 * Paper's defaults while everything drawn inside them has moved.
 */
export function navigationColors(value, isDark) {
  const colors = schemeColors(value, isDark);
  return {
    primary: colors.primary,
    background: colors.background,
    card: colors.elevation.level2,
    text: colors.onSurface,
    border: colors.outlineVariant,
    notification: colors.error,
  };
}

/** The three seeds, for the swatch a scheme is chosen by. */
export function schemeSwatch(value, isDark) {
  const colors = schemeColors(value, isDark);
  return [colors.primary, colors.secondary, colors.tertiary];
}
